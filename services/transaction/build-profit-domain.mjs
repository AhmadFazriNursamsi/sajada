// Run from any directory after root dependencies are installed.
// Generated runtime reuses the exact tested frontend domain, without TS runtime support.
import ts from '../../node_modules/typescript/lib/typescript.js';
import {readFile,writeFile} from 'node:fs/promises';
const files=['tiered-sharing.ts','funding.ts'];
const source=(await Promise.all(files.map(f=>readFile(new URL('../../shared/'+f,import.meta.url),'utf8')))).join('\n');
const output=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
await writeFile(new URL('./profit-domain.mjs',import.meta.url),'// Generated by build-profit-domain.mjs from shared domain modules.\n'+output);
